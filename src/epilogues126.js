function terminal(c){
 if(!c||!c.player)return false;
 if(c.ending==='gate')return c.stage>=7&&['seriesResult','registration'].includes(c.status);
 return ['sgChampion','sgFinished'].includes(c.ending)&&c.stage===8&&!!c.series?.completed;
}
function classify(c){
 if(!terminal(c))return null;
 if(c.ending==='gate')return {outcome:'other',reason:'gate',finalPlace:null,raceId:null};
 const summary=[...(c.history||[])].reverse().find(x=>x.stage===8),r=c.series?.race,z=c.lastResult;
 const place=Number.isInteger(summary?.finalPlace)&&summary.finalPlace>=1&&summary.finalPlace<=6?summary.finalPlace:null;
 const info={outcome:'other',reason:'unverified',finalPlace:place,raceId:typeof r?.id==='string'?r.id:null};
 if(summary?.finalType==='eliminated')return {...info,reason:'eliminated',finalPlace:null};
 if(summary?.finalType!=='championship')return {...info,reason:summary?.finalType==='consolation'?'consolation':'unverified'};
 // A clean placing needs the actual championship result; a historical champion flag alone is insufficient.
 if(!r?.done||r.type!=='championship'||z?.type!=='championship'||z.raceId!==r.id)return info;
 const own=(z.finish||[]).find(x=>x.id===c.player.id||x.isPlayer),boat=(r.runners||[]).find(x=>x.id===c.player.id||x.isPlayer);
 if(z.startFault||own?.startFault||boat?.startFault)return {...info,reason:'startFault'};
 if(z.capsized||own?.capsized||boat?.capsized)return {...info,reason:'capsized'};
 if(z.dnf||own?.dnf||boat?.dnf)return {...info,reason:'dnf'};
 if(!own||place===null||z.place!==place||own.place!==place)return info;
 return {...info,outcome:place===1?'win':'placed',reason:'finish'};
}
